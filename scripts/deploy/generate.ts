// Generate a Worker's Wrangler config from the checked-in wrangler.toml: take the [env.production]
// view of the file (what `wrangler deploy --env production` would use) and substitute this
// instance's names, ids and addresses. The checked-in files are never edited.
import { join } from "node:path";

export interface Section {
  header: string | null;
  lines: string[];
}

export function parseSections(text: string): Section[] {
  const sections: Section[] = [{ header: null, lines: [] }];
  for (const line of text.split("\n")) {
    if (/^\[\[?[A-Za-z]/.test(line)) sections.push({ header: line.trim(), lines: [] });
    else sections.at(-1)!.lines.push(line);
  }
  return sections;
}

const bare = (h: string) => h.replace(/^\[+/, "").replace(/\]+$/, "");
const isEnv = (h: string | null) => !!h && bare(h).startsWith("env.");
const prodHeader = (h: string) => {
  const b = bare(h);
  return b.startsWith("env.production.") ? h.replace("env.production.", "") : null;
};

export interface Substitutions {
  name: string; // instance name
  workerName: string;
  url: string;
  kvId: string;
  /** Absolute directory of the app, so main and assets paths work from the generated file's location. */
  appDir: string;
  passport: { on: boolean; url?: string };
}

/** Keys at column 0 and the lines of their (possibly multi-line) value. */
function setKey(lines: string[], key: string, value: string | null): string[] {
  const out: string[] = [];
  let skipping = false;
  let done = false;
  for (const line of lines) {
    const m = /^([A-Za-z_][A-Za-z0-9_.]*)\s*=/.exec(line);
    if (m) {
      skipping = false;
      if (m[1] === key) {
        if (value !== null) out.push(`${key} = ${value}`);
        done = true;
        skipping = /=\s*\[\s*$/.test(line) || (line.includes("[") && !line.includes("]"));
        continue;
      }
    } else if (skipping) {
      if (/^\s*\]/.test(line)) skipping = false;
      continue;
    }
    out.push(line);
  }
  if (!done && value !== null) {
    out.push(`${key} = ${value}`);
  }
  return out;
}

export function generateConfig(baseText: string, sub: Substitutions): string {
  const sections = parseSections(baseText);
  const prod = new Map<string, Section[]>();
  for (const s of sections) {
    if (!s.header) continue;
    const h = prodHeader(s.header);
    if (h) prod.set(bare(h), [...(prod.get(bare(h)) ?? []), { header: h, lines: s.lines }]);
  }
  const out: string[] = [];
  const emitted = new Set<string>();
  const baseTop = sections[0]!.lines;
  let top = baseTop;
  top = setKey(top, "name", JSON.stringify(sub.workerName));
  top = setKey(top, "workers_dev", "false");
  top = setKey(top, "main", JSON.stringify(join(sub.appDir, "src", "index.ts")));
  out.push(...top);
  for (const s of sections) {
    if (!s.header || isEnv(s.header)) continue;
    const key = bare(s.header);
    const replacement = prod.get(key);
    if (replacement) {
      if (emitted.has(key)) continue;
      emitted.add(key);
      for (const r of replacement) out.push(r.header!, ...r.lines);
    } else {
      let lines = s.lines;
      if (key === "assets") lines = setKey(lines, "directory", JSON.stringify(join(sub.appDir, "public")));
      out.push(s.header, ...lines);
    }
  }
  // Production sections the base has no top-level twin for.
  for (const [key, list] of prod) if (!emitted.has(key) && !sections.some((s) => s.header && bare(s.header) === key)) for (const r of list) out.push(r.header!, ...r.lines);

  let text = out.join("\n");
  const n = sub.name;
  text = text
    .replace(/bucket_name = "gms-([a-z-]+)"/g, (_m, rest: string) => `bucket_name = "${n}-${rest}"`)
    .replace(/^(queue|dead_letter_queue) = "gms-([a-z-]+)"/gm, (_m, k: string, rest: string) => `${k} = "${n}-${rest}"`)
    .replace(/^(\s*binding = "RATE_LIMIT"\nid = )"[0-9a-f]{32}"/m, `$1"${sub.kvId}"`)
    .replace(/^(GMS_BASE_URL|WEB_BASE_URL|OAUTH_ISSUER) = ".*"$/gm, `$1 = "${sub.url}"`);
  if (!sub.passport.on) text = text.replace(/^PASSPORT_[A-Z_]+ = ".*"\n/gm, "");
  else if (sub.passport.url && sub.passport.url !== "https://passport.opengrants.io") text = text.replace(/^(PASSPORT_BASE_URL|PASSPORT_ISSUER) = ".*"$/gm, `$1 = "${sub.passport.url}"`);
  return text.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

export const HEADER = (what: string) => `# Generated by scripts/deploy (${what}). Do not edit; re-run the cloudflare step.\n# Derived from the checked-in wrangler.toml, [env.production] view.\n`;
