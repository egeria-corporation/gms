#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
// Builds a single "front" Worker for an environment whose deploy token cannot upload static
// assets or edit zone routes (see docs/decisions.md, 2026-11-10). The Worker:
//   - serves the built web app (apps/web/dist) from files embedded in its own script, with the
//     SPA fallback and the headers from dist/_headers;
//   - forwards the API path prefixes to the API Worker over a service binding,
// so one custom domain gives the web app and the API the same origin, as the production routes do.
//
//   node scripts/build-front-worker.mjs --name gms-web-staging --host gms.opengrants.io --api gms-api-staging \
//     [--redirect-from gms-staging.opengrants.io]   an old address that permanently redirects to --host
//
// Writes apps/web/.front-worker/{index.js,assets.js,wrangler.toml}; deploy with
//   pnpm --filter @gms/web exec wrangler deploy --config .front-worker/wrangler.toml
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith("--") ? [...acc, [a.slice(2), all[i + 1]]] : acc), []));
for (const required of ["name", "host", "api"]) {
  if (!args[required]) {
    console.error(`Missing --${required}`);
    process.exit(1);
  }
}

const web = fileURLToPath(new URL("../apps/web/", import.meta.url));
const dist = join(web, "dist");
const out = join(web, ".front-worker");

const TYPES = {
  html: "text/html; charset=utf-8",
  js: "text/javascript; charset=utf-8",
  css: "text/css; charset=utf-8",
  json: "application/json",
  png: "image/png",
  svg: "image/svg+xml",
  ico: "image/x-icon",
  ttf: "font/ttf",
  woff2: "font/woff2",
  txt: "text/plain; charset=utf-8",
  map: "application/json",
};

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) yield* walk(full);
    else yield full;
  }
}

// dist/_headers: a path pattern line, then indented "Name: value" lines.
function parseHeaders(text) {
  const rules = [];
  let current = null;
  for (const line of text.split("\n")) {
    if (!line.trim() || line.trim().startsWith("#")) continue;
    if (/^\s/.test(line)) {
      const i = line.indexOf(":");
      if (current && i > 0) current.headers[line.slice(0, i).trim()] = line.slice(i + 1).trim();
    } else {
      current = { pattern: line.trim(), headers: {} };
      rules.push(current);
    }
  }
  return rules;
}

const files = {};
let headerRules = [];
let bytes = 0;
for (const full of walk(dist)) {
  const path = "/" + relative(dist, full).split(sep).join("/");
  if (path === "/_headers") {
    headerRules = parseHeaders(readFileSync(full, "utf8"));
    continue;
  }
  const body = readFileSync(full);
  bytes += body.length;
  files[path] = { type: TYPES[path.split(".").pop().toLowerCase()] ?? "application/octet-stream", body: body.toString("base64") };
}
if (!files["/index.html"]) {
  console.error("apps/web/dist/index.html is missing. Build the web app first.");
  process.exit(1);
}

mkdirSync(out, { recursive: true });
writeFileSync(join(out, "assets.js"), `export const FILES = ${JSON.stringify(files)};\nexport const HEADER_RULES = ${JSON.stringify(headerRules)};\n`);

writeFileSync(
  join(out, "index.js"),
  `// Generated by scripts/build-front-worker.mjs. Do not edit.
import { FILES, HEADER_RULES } from "./assets.js";

// The API Worker's paths (apps/api/wrangler.toml, [env.production] routes).
const API_PREFIXES = ["/common-grants/", "/gms/", "/oauth/", "/.well-known/", "/webhooks/"];
const API_EXACT = ["/llms.txt", "/llms-full.txt", "/openapi.json", "/sitemap.xml", "/health"];
const isApi = (path) => API_EXACT.includes(path) || path === "/mcp" || path.startsWith("/mcp/") || API_PREFIXES.some((p) => path.startsWith(p));

const decoded = new Map();
function bodyOf(path) {
  let bytes = decoded.get(path);
  if (!bytes) {
    const raw = atob(FILES[path].body);
    bytes = new Uint8Array(raw.length);
    for (let i = 0; i < raw.length; i++) bytes[i] = raw.charCodeAt(i);
    decoded.set(path, bytes);
  }
  return bytes;
}

function matches(pattern, path) {
  return pattern.endsWith("*") ? path.startsWith(pattern.slice(0, -1)) : pattern === path;
}

const HOST = ${JSON.stringify(args.host)};
const REDIRECT_FROM = ${JSON.stringify(args["redirect-from"] ?? null)};

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    // The old address: send people (and their bookmarks) to the same page on the new one.
    if (REDIRECT_FROM && url.hostname === REDIRECT_FROM) {
      url.hostname = HOST;
      return Response.redirect(url.toString(), 308);
    }
    if (isApi(url.pathname)) return env.API.fetch(request);
    if (request.method !== "GET" && request.method !== "HEAD") return new Response("Method not allowed", { status: 405, headers: { Allow: "GET, HEAD" } });

    // A path with a file extension that is not a known file is a 404; every other path is the app.
    let path = url.pathname;
    if (!FILES[path]) {
      if (/\\.[a-z0-9]+$/i.test(path)) return new Response("Not found", { status: 404 });
      path = "/index.html";
    }
    const headers = new Headers({ "Content-Type": FILES[path].type });
    if (path === "/index.html") headers.set("Cache-Control", "no-cache");
    for (const rule of HEADER_RULES) {
      if (matches(rule.pattern, path)) for (const [k, v] of Object.entries(rule.headers)) headers.set(k, v);
    }
    return new Response(request.method === "HEAD" ? null : bodyOf(path), { headers });
  },
};
`,
);

writeFileSync(
  join(out, "wrangler.toml"),
  `# Generated by scripts/build-front-worker.mjs. Do not edit.
name = "${args.name}"
main = "index.js"
compatibility_date = "2026-10-01"
workers_dev = false
routes = [{ pattern = "${args.host}", custom_domain = true }${args["redirect-from"] ? `, { pattern = "${args["redirect-from"]}", custom_domain = true }` : ""}]

[[services]]
binding = "API"
service = "${args.api}"

[observability]
enabled = true
`,
);

console.log(`front worker: ${Object.keys(files).length} files, ${(bytes / 1024 / 1024).toFixed(2)} MB before encoding, ${headerRules.length} header rules`);
