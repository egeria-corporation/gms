#!/usr/bin/env node
// SPDX-License-Identifier: AGPL-3.0-only
// Writes src/database.types.ts (the Supabase `Database` shape) from a live Postgres that has the
// migrations applied. Uses the psql CLI so the package needs no driver dependency.
//
//   DATABASE_URL=postgres://postgres:postgres@127.0.0.1:57322/postgres node scripts/gen-types.mjs
//
// `supabase gen types typescript --local` produces the same shape (plus enums and relationships)
// and may replace this script once the local stack is the norm.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("DATABASE_URL is not set");
  process.exit(1);
}

const sql = `
  select c.table_name, c.column_name, c.udt_name, c.is_nullable, (c.column_default is not null) as has_default
  from information_schema.columns c
  join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.column_name`;
const out = execFileSync("psql", [url, "-At", "-F", "\t", "-c", sql], { encoding: "utf8" });

const TS = {
  uuid: "string",
  text: "string",
  varchar: "string",
  timestamptz: "string",
  date: "string",
  int2: "number",
  int4: "number",
  int8: "number",
  numeric: "number",
  float8: "number",
  bool: "boolean",
  jsonb: "Json",
  json: "Json",
};
const tsType = (udt) => {
  if (udt.startsWith("_")) return `${tsType(udt.slice(1))}[]`;
  const t = TS[udt];
  if (!t) throw new Error(`gen-types: no mapping for Postgres type ${udt}`);
  return t;
};

const tables = new Map();
for (const line of out.split("\n").filter(Boolean)) {
  const [table, column, udt, nullable, hasDefault] = line.split("\t");
  if (!tables.has(table)) tables.set(table, []);
  tables.get(table).push({ column, type: tsType(udt), nullable: nullable === "YES", hasDefault: hasDefault === "t" });
}

const lines = [];
lines.push("// SPDX-License-Identifier: AGPL-3.0-only");
lines.push("// GENERATED by packages/db/scripts/gen-types.mjs from supabase/migrations. Do not edit by hand.");
lines.push("");
lines.push("export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];");
lines.push("");
lines.push("export type Database = {");
lines.push("  public: {");
lines.push("    Tables: {");
for (const [table, cols] of tables) {
  lines.push(`      ${table}: {`);
  lines.push("        Row: {");
  for (const c of cols) lines.push(`          ${c.column}: ${c.type}${c.nullable ? " | null" : ""};`);
  lines.push("        };");
  lines.push("        Insert: {");
  for (const c of cols) {
    const optional = c.nullable || c.hasDefault;
    lines.push(`          ${c.column}${optional ? "?" : ""}: ${c.type}${c.nullable ? " | null" : ""};`);
  }
  lines.push("        };");
  lines.push("        Update: {");
  for (const c of cols) lines.push(`          ${c.column}?: ${c.type}${c.nullable ? " | null" : ""};`);
  lines.push("        };");
  lines.push("        Relationships: [];");
  lines.push("      };");
}
lines.push("    };");
lines.push("    Views: { [_ in never]: never };");
lines.push("    Functions: { [_ in never]: never };");
lines.push("    Enums: { [_ in never]: never };");
lines.push("    CompositeTypes: { [_ in never]: never };");
lines.push("  };");
lines.push("};");
lines.push("");
lines.push("type PublicTables = Database[\"public\"][\"Tables\"];");
lines.push("export type TableName = keyof PublicTables;");
lines.push("export type Tables<T extends TableName> = PublicTables[T][\"Row\"];");
lines.push("export type TablesInsert<T extends TableName> = PublicTables[T][\"Insert\"];");
lines.push("export type TablesUpdate<T extends TableName> = PublicTables[T][\"Update\"];");
lines.push("");
lines.push(`export const TABLE_NAMES = ${JSON.stringify([...tables.keys()])} as const satisfies readonly TableName[];`);
lines.push("");

const target = fileURLToPath(new URL("../src/database.types.ts", import.meta.url));
writeFileSync(target, lines.join("\n"));
console.log(`wrote ${target} (${tables.size} tables)`);
